_ROOT = Path(__file__).resolve().parents[2]
_SCRIPTS = _ROOT / "scripts"
_SCRIPT = _SCRIPTS / "run_local_rc.py"
if str(_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS))

_SPEC = importlib.util.spec_from_file_location("praxis_local_rc_runner", _SCRIPT)
assert _SPEC and _SPEC.loader
runner = importlib.util.module_from_spec(_SPEC)
sys.modules[_SPEC.name] = runner
_SPEC.loader.exec_module(runner)


def _git(repo: Path, *arguments: str) -> str:
    result = subprocess.run(
        ["git", *arguments],
        cwd=repo,
        capture_output=True,
        check=False,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    return result.stdout.strip()


def _lock(path: Path, name: str) -> None:
    path.write_text(
        "\n".join(
            (
                "# This file is autogenerated by pip-compile with Python 3.13",
                f"{name}==1.0.0 \\",
                f"    --hash=sha256:{'a' * 64}",
                "",
            )
        ),
        encoding="utf-8",
    )


def _clean_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "source"
    (repo / "requirements").mkdir(parents=True)
    (repo / "scripts").mkdir()
    (repo / "praxis_virtualcell").mkdir()
    shutil.copy2(
        _ROOT / "scripts" / "build_release_source_archive.sh", repo / "scripts" / "build_release_source_archive.sh"
    )
    (repo / "scripts" / "build_release_source_archive.sh").chmod(0o755)
    (repo / "pyproject.toml").write_text(
        '[project]\nname = "fixture"\nversion = "0.0.0"\n',
        encoding="utf-8",
    )
    (repo / "praxis_virtualcell" / "__init__.py").write_text('__version__ = "0.0.0"\n', encoding="utf-8")
    _lock(repo / "requirements" / "build-py313.lock", "missing-build")
    _lock(repo / "requirements" / "runtime-py313.lock", "missing-runtime")
    _git(repo, "init", "-q")
    _git(repo, "config", "user.name", "P30 Test")
    _git(repo, "config", "user.email", "p30@example.invalid")
    _git(repo, "add", "pyproject.toml", "requirements", "scripts", "praxis_virtualcell")
    _git(repo, "commit", "-qm", "fixture")
    return repo


def _configure(monkeypatch: pytest.MonkeyPatch, repo: Path) -> None:
    monkeypatch.setattr(runner, "_RUNNER_REPO_ROOT", repo)
    monkeypatch.setattr(runner.preflight, "_FINALIZER_REPO_ROOT", repo)


def _empty_caches(tmp_path: Path) -> tuple[Path, Path]:
    pip_cache = tmp_path / "pip-cache"
    npm_cache = tmp_path / "npm-cache"
    pip_cache.mkdir()
    npm_cache.mkdir()
    return pip_cache, npm_cache


def test_runner_interface_is_closed_to_caller_claims() -> None:
    parsed = runner._parser().parse_args(["--output", "/tmp/praxis-local-rc"])

    assert vars(parsed) == {
        "output": Path("/tmp/praxis-local-rc"),
        "pip_cache_root": None,
        "npm_cache_root": None,
    }
    assert set(inspect.signature(runner.run_local_rc).parameters) == {
        "output_dir",
        "pip_cache_root",
        "npm_cache_root",
    }
    with pytest.raises(SystemExit):
        runner._parser().parse_args(["--output", "/tmp/praxis-local-rc", "--artifact", "/tmp/fake.whl"])


def test_clean_source_builds_two_identical_archives_but_never_forms_an_rc(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    pip_cache, npm_cache = _empty_caches(tmp_path)
    output = tmp_path / "local-rc"
    _configure(monkeypatch, repo)

    record = runner.run_local_rc(
        output_dir=output,
        pip_cache_root=pip_cache,
        npm_cache_root=npm_cache,
    )

    archived = record["artifacts"]["source_archive"]
    assert record["status"] == "LOCAL_RC_INCOMPLETE"
    assert record["software_rc_gates_passed"] is False
    assert record["full_gate_execution"] == "SOURCE_ARCHIVE_ONLY_NOT_FULL_RC"
    assert record["source"]["observed_stable_during_runner"] is True
    assert archived["status"] == "passed_engineering_evidence_only"
    assert archived["reason_code"] == "byte_identical"
    assert archived["first"]["sha256"] == archived["second"]["sha256"]
    assert archived["first"]["relative_path"].startswith("artifacts/")
    serialized = json.dumps(record)
    assert str(repo) not in serialized
    assert str(pip_cache) not in serialized
    assert str(npm_cache) not in serialized
    persisted = json.loads((output / "local-rc-runner-record.json").read_text(encoding="utf-8"))
    assert persisted == record
    assert _git(repo, "status", "--porcelain=v1", "--untracked-files=normal") == ""


