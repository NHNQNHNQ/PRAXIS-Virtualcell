def test_tampered_preflight_record_cannot_enter_the_runner_record(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    pip_cache, npm_cache = _empty_caches(tmp_path)
    _configure(monkeypatch, repo)
    original = runner.preflight.finalize_local_rc

    def write_then_tamper(**kwargs):
        result = original(**kwargs)
        path = kwargs["output_dir"] / "finalizer-record.json"
        raw = json.loads(path.read_text(encoding="utf-8"))
        raw["published"] = True
        path.write_text(json.dumps(raw), encoding="utf-8")
        return result

    monkeypatch.setattr(runner.preflight, "finalize_local_rc", write_then_tamper)
    output = tmp_path / "local-rc"

    with pytest.raises(runner.LocalRcRunnerError, match="negative invariants"):
        runner.run_local_rc(
            output_dir=output,
            pip_cache_root=pip_cache,
            npm_cache_root=npm_cache,
        )
    assert not (output / "local-rc-runner-record.json").exists()


