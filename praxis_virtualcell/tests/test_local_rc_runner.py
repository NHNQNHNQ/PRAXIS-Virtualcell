def test_live_builder_mutation_never_executes_after_head_snapshot(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    pip_cache, npm_cache = _empty_caches(tmp_path)
    _configure(monkeypatch, repo)
    original = runner._snapshot_builder
    sentinel = tmp_path / "live-builder-ran"

    def snapshot_then_mutate(*args, **kwargs):
        snapshot = original(*args, **kwargs)
        (repo / "scripts" / "build_release_source_archive.sh").write_text(
            f"#!/bin/bash\ntouch {sentinel}\n",
            encoding="utf-8",
        )
        return snapshot

    monkeypatch.setattr(runner, "_snapshot_builder", snapshot_then_mutate)
    record = runner.run_local_rc(
        output_dir=tmp_path / "local-rc",
        pip_cache_root=pip_cache,
        npm_cache_root=npm_cache,
    )

    assert not sentinel.exists()
    assert record["artifacts"]["source_archive"]["status"] == "invalidated_source_drift"


def test_injected_artifact_directory_symlink_cannot_redirect_archive_output(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    pip_cache, npm_cache = _empty_caches(tmp_path)
    _configure(monkeypatch, repo)
    original = runner.preflight.finalize_local_rc
    outside = tmp_path / "outside"
    outside.mkdir()

    def write_then_inject(*, output_dir, **kwargs):
        result = original(output_dir=output_dir, **kwargs)
        (output_dir.parent / "artifacts").symlink_to(outside, target_is_directory=True)
        return result

    monkeypatch.setattr(runner.preflight, "finalize_local_rc", write_then_inject)
    record = runner.run_local_rc(
        output_dir=tmp_path / "local-rc",
        pip_cache_root=pip_cache,
        npm_cache_root=npm_cache,
    )

    assert record["artifacts"]["source_archive"] == {
        "status": "blocked_dependency",
        "reason_code": "controlled_artifact_directory_unavailable",
    }
    assert list(outside.iterdir()) == []


def test_runner_ignores_hostile_git_and_path_environment(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    pip_cache, npm_cache = _empty_caches(tmp_path)
    hostile_bin = tmp_path / "hostile-bin"
    sentinel = tmp_path / "hostile-git-ran"
    hostile_bin.mkdir()
    (hostile_bin / "git").write_text(f"#!/bin/bash\ntouch {sentinel}\nexit 1\n", encoding="utf-8")
    (hostile_bin / "git").chmod(0o755)
    _configure(monkeypatch, repo)
    monkeypatch.setenv("PATH", str(hostile_bin))
    monkeypatch.setenv("GIT_DIR", str(tmp_path / "forged-git-dir"))
    previous = os.environ.get("PATH")

    record = runner.run_local_rc(
        output_dir=tmp_path / "local-rc",
        pip_cache_root=pip_cache,
        npm_cache_root=npm_cache,
    )

    assert record["artifacts"]["source_archive"]["status"] == "passed_engineering_evidence_only"
    assert not sentinel.exists()
    assert os.environ.get("PATH") == previous


def test_source_drift_invalidates_even_byte_identical_archives(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    pip_cache, npm_cache = _empty_caches(tmp_path)
    _configure(monkeypatch, repo)
    original = runner._build_source_archive
    calls = 0

    def build_then_drift(**kwargs):
        nonlocal calls
        calls += 1
        result = original(**kwargs)
        if calls == 1:
            (repo / "late-user-change.txt").write_text("drift\n", encoding="utf-8")
        return result

    monkeypatch.setattr(runner, "_build_source_archive", build_then_drift)
    record = runner.run_local_rc(
        output_dir=tmp_path / "local-rc",
        pip_cache_root=pip_cache,
        npm_cache_root=npm_cache,
    )

    assert record["source"]["observed_stable_during_runner"] is False
    assert record["artifacts"]["source_archive"]["status"] == "invalidated_source_drift"
    assert record["software_rc_gates_passed"] is False


def test_runner_rejects_reused_and_in_tree_output_without_source_mutation(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    _configure(monkeypatch, repo)
    before = _git(repo, "status", "--porcelain=v1", "--untracked-files=normal")

    with pytest.raises(preflight_error := runner.preflight.FinalizerError, match="outside source"):
        runner.run_local_rc(output_dir=repo / "out")
    reused = tmp_path / "reused"
    reused.mkdir()
    with pytest.raises(preflight_error, match="write-new"):
        runner.run_local_rc(output_dir=reused)
    assert _git(repo, "status", "--porcelain=v1", "--untracked-files=normal") == before == ""


