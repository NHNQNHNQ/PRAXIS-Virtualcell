from __future__ import annotations

import importlib.util
import inspect
import json
import subprocess
import sys
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[2]
_SCRIPT = _ROOT / "scripts" / "finalize_local_rc.py"
_SCRIPTS = _ROOT / "scripts"
if str(_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS))

_SPEC = importlib.util.spec_from_file_location("praxis_release_finalizer", _SCRIPT)
assert _SPEC and _SPEC.loader
finalizer = importlib.util.module_from_spec(_SPEC)
sys.modules[_SPEC.name] = finalizer
_SPEC.loader.exec_module(finalizer)


def _run(repo: Path, *arguments: str) -> str:
    result = subprocess.run(
        ["git", *arguments],
        cwd=repo,
        capture_output=True,
        check=False,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    return result.stdout.strip()


def _lock(path: Path, name: str) -> None:
    path.write_text(
        "\n".join(
            (
                "# This file is autogenerated by pip-compile with Python 3.13",
                f"{name}==1.0.0 \\",
                f"    --hash=sha256:{'a' * 64}",
                "",
            )
        ),
        encoding="utf-8",
    )


def _clean_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "source"
    (repo / "requirements").mkdir(parents=True)
    (repo / "pyproject.toml").write_text(
        '[project]\nname = "fixture"\nversion = "0.0.0"\n',
        encoding="utf-8",
    )
    _lock(repo / "requirements" / "build-py313.lock", "missing-build")
    _lock(repo / "requirements" / "runtime-py313.lock", "missing-runtime")
    _run(repo, "init", "-q")
    _run(repo, "config", "user.name", "P30 Test")
    _run(repo, "config", "user.email", "p30@example.invalid")
    _run(repo, "add", "pyproject.toml", "requirements")
    _run(repo, "commit", "-qm", "fixture")
    return repo


def test_finalizer_parser_and_callable_are_closed_to_caller_claims() -> None:
    parsed = finalizer._parser().parse_args(["--output", "/tmp/praxis-finalizer-output"])

    assert vars(parsed) == {
        "output": Path("/tmp/praxis-finalizer-output"),
        "pip_cache_root": None,
        "npm_cache_root": None,
    }
    assert set(inspect.signature(finalizer.finalize_local_rc).parameters) == {
        "output_dir",
        "pip_cache_root",
        "npm_cache_root",
    }
    with pytest.raises(SystemExit):
        finalizer._parser().parse_args(["--output", "/tmp/praxis-finalizer-output", "--artifact", "/tmp/claimed.whl"])


def test_finalizer_rejects_in_tree_or_reused_output_without_mutating_source(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    monkeypatch.setattr(finalizer, "_FINALIZER_REPO_ROOT", repo)
    before = _run(repo, "status", "--porcelain=v1", "--untracked-files=normal")

    with pytest.raises(finalizer.FinalizerError, match="outside source"):
        finalizer.finalize_local_rc(output_dir=repo / "out")

    reused = tmp_path / "reused"
    reused.mkdir()
    with pytest.raises(finalizer.FinalizerError, match="write-new"):
        finalizer.finalize_local_rc(output_dir=reused)

    protected = tmp_path / "protected"
    protected.mkdir()
    monkeypatch.setattr(finalizer, "_PROTECTED_OUTPUT_ROOTS", (protected,))
    with pytest.raises(finalizer.FinalizerError, match="protected roots"):
        finalizer.finalize_local_rc(output_dir=protected / "release-preflight")

    assert _run(repo, "status", "--porcelain=v1", "--untracked-files=normal") == before == ""


def test_finalizer_creates_a_private_new_output_directory(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    output = tmp_path / "release-preflight"
    pip_cache = tmp_path / "empty-pip-cache"
    npm_cache = tmp_path / "empty-npm-cache"
    pip_cache.mkdir()
    npm_cache.mkdir()
    monkeypatch.setattr(finalizer, "_FINALIZER_REPO_ROOT", repo)

    finalizer.finalize_local_rc(
        output_dir=output,
        pip_cache_root=pip_cache,
        npm_cache_root=npm_cache,
    )

    assert output.is_dir()
    assert output.stat().st_mode & 0o777 == 0o700
    assert (output / "finalizer-record.json").is_file()


def test_missing_offline_cache_writes_structured_incomplete_record_without_source_mutation(
    tmp_path: Path,
    monkeypatch,
) -> None:
    repo = _clean_repo(tmp_path)
    pip_cache = tmp_path / "empty-pip-cache"
    npm_cache = tmp_path / "empty-npm-cache"
    output = tmp_path / "release-preflight"
    pip_cache.mkdir()
    npm_cache.mkdir()
    monkeypatch.setattr(finalizer, "_FINALIZER_REPO_ROOT", repo)
    before_head = _run(repo, "rev-parse", "HEAD")
    before_status = _run(repo, "status", "--porcelain=v1", "--untracked-files=normal")

    result = finalizer.finalize_local_rc(
        output_dir=output,
        pip_cache_root=pip_cache,
        npm_cache_root=npm_cache,
    )

    record_path = output / "finalizer-record.json"
    record = json.loads(record_path.read_text(encoding="utf-8"))
    assert record == result
    assert record["status"] == "LOCAL_RC_INCOMPLETE"
    assert record["software_rc_gates_passed"] is False
    assert record["full_gate_execution"] == "PRECHECK_ONLY_NOT_EXECUTED"
    assert record["source"]["observed_stable_during_preflight"] is True
    assert record["source"]["not_attestation"] is True
    assert record["source"]["future_execution_must_reverify"] is True
    assert record["source"]["pre_exact"]["source_sha"] == before_head
    assert record["interpreter"]["exact_cpython313"] is True
    assert record["dependency_preflight"]["npm_cache"] == {
        "status": "path_available_not_coverage_validated",
        "identity": "local_cache_path_not_serialized",
    }
    assert str(npm_cache) not in record_path.read_text(encoding="utf-8")
    blockers = record["blockers"]
    assert {(item["code"], item.get("target_profile")) for item in blockers} >= {
        ("offline_wheel_cache_incomplete", "macos_arm64_cp313"),
        ("offline_wheel_cache_incomplete", "linux_arm64_cp313"),
    }
    assert record["gates"]["wheel"]["status"] == "blocked_dependency"
    assert record["gates"]["container"]["status"] == "blocked_dependency"
    assert record["gates"]["container"] == {
        "status": "blocked_dependency",
        "reason_code": "offline_wheel_cache_incomplete",
    }
    assert _run(repo, "rev-parse", "HEAD") == before_head
    assert _run(repo, "status", "--porcelain=v1", "--untracked-files=normal") == before_status == ""


def test_dirty_source_still_writes_a_negative_record(tmp_path: Path, monkeypatch) -> None:
    repo = _clean_repo(tmp_path)
    output = tmp_path / "release-preflight"
    (repo / "untracked.txt").write_text("protected user state\n", encoding="utf-8")
    monkeypatch.setattr(finalizer, "_FINALIZER_REPO_ROOT", repo)

    record = finalizer.finalize_local_rc(output_dir=output)

    assert record["status"] == "LOCAL_RC_INCOMPLETE"
    assert record["source"]["pre_exact"] is None
    assert record["source"]["observed_stable_during_preflight"] is False
    assert {item["code"] for item in record["blockers"]} == {"source_not_clean_exact_head"}
    assert (output / "finalizer-record.json").is_file()
    assert {gate["status"] for gate in record["gates"].values()} == {"blocked_dependency"}


def test_record_creation_is_exclusive_even_if_a_prior_check_lies(tmp_path: Path, monkeypatch) -> None:
    output = tmp_path / "release-preflight"
    output.mkdir()
    record_path = output / "finalizer-record.json"
    record_path.write_text("user-owned record\n", encoding="utf-8")
    original_exists = Path.exists

    def _pretend_missing(path: Path) -> bool:
        return False if path == record_path else original_exists(path)

    monkeypatch.setattr(Path, "exists", _pretend_missing)
    with pytest.raises(finalizer.FinalizerError, match="already exists"):
        finalizer._write_new_record(output, {"status": "LOCAL_RC_INCOMPLETE"})
    assert record_path.read_text(encoding="utf-8") == "user-owned record\n"


def test_gate_records_do_not_understate_missing_offline_dependencies() -> None:
    wheelhouse_missing = finalizer._gate_records(
        [
            {
                "code": "offline_wheel_cache_unavailable",
                "dependency": "hash_locked_python_wheels",
                "detail": "pip cache root is unavailable",
            }
        ],
        npm_cache_available=True,
    )
    npm_missing = finalizer._gate_records([], npm_cache_available=False)
    source_changed = finalizer._gate_records(
        [
            {
                "code": "source_identity_changed_during_preflight",
                "dependency": "exact_committed_source",
                "detail": "source changed",
            }
        ],
        npm_cache_available=True,
    )

    assert wheelhouse_missing["wheel"] == {
        "status": "blocked_dependency",
        "reason_code": "offline_wheel_cache_unavailable",
    }
    assert wheelhouse_missing["container"] == {
        "status": "blocked_dependency",
        "reason_code": "offline_wheel_cache_unavailable",
    }
    assert npm_missing["frontend"] == {
        "status": "blocked_dependency",
        "reason_code": "offline_npm_cache_unavailable",
    }
    assert npm_missing["wheel"] == {
        "status": "blocked_dependency",
        "reason_code": "offline_npm_cache_unavailable",
    }
    assert npm_missing["container"] == {
        "status": "blocked_dependency",
        "reason_code": "offline_npm_cache_unavailable",
    }
    assert {gate["status"] for gate in source_changed.values()} == {"blocked_dependency"}
    assert {gate["reason_code"] for gate in source_changed.values()} == {"source_or_interpreter_preflight_failed"}


