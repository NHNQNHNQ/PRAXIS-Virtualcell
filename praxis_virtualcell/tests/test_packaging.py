"""打包配置守卫:wheel 必须含 praxis_virtualcell/praxis_vc_api + 运行时数据。
防 packages.find 回退到只打 praxis2(否则 praxis-vc CLI ImportError)。"""
import json
import re
import tomllib
from importlib.resources import files
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]


def test_packages_find_includes_virtualcell():
    cfg = tomllib.loads((_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    include = cfg["tool"]["setuptools"]["packages"]["find"]["include"]
    assert any(p.startswith("praxis_virtualcell") for p in include), include
    assert any(p.startswith("praxis_vc_api") for p in include), include


def test_include_package_data_and_manifest():
    cfg = tomllib.loads((_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    assert cfg["tool"]["setuptools"].get("include-package-data") is True
    manifest = (_ROOT / "MANIFEST.in").read_text(encoding="utf-8")
    assert "recursive-include praxis_virtualcell" in manifest
    assert "*.md" in manifest


def test_default_gene_sets_are_licensed_package_resources():
    resource_dir = files("praxis_virtualcell").joinpath("data", "module_gene_sets")
    expected = {
        "membrane_system.json",
        "biosynthetic_network.json",
        "degradation_machinery.json",
    }
    for name in expected:
        doc = json.loads(resource_dir.joinpath(name).read_text(encoding="utf-8"))
        assert doc["license"] == "MIT (this qualitative mapping only)"
        assert doc["gene_set"]

    assert not list((_ROOT / "data" / "module_gene_sets").glob("*.json"))


def _locked_names(path: Path) -> set[str]:
    text = path.read_text(encoding="utf-8")
    assert "autogenerated by pip-compile with Python 3.13" in text
    assert "--hash=sha256:" in text
    assert "--index-url" not in text
    names: set[str] = set()
    for line in text.splitlines():
        if not line or line[0].isspace() or line.startswith("#"):
            continue
        match = re.match(r"([A-Za-z0-9_.-]+)==[^ ]+ \\$", line)
        assert match, f"non-exact lock entry in {path}: {line!r}"
        names.add(match.group(1).lower().replace("_", "-"))
    return names


def test_python313_hash_locks_cover_ci_and_runtime_dependencies():
    runtime = _locked_names(_ROOT / "requirements" / "runtime-py313.lock")
    dev = _locked_names(_ROOT / "requirements" / "dev-py313.lock")

    assert {"fastapi", "httpx", "mcp", "pydantic", "uvicorn"} <= runtime
    assert {"pytest", "ruff", "httpx2", "streamlit", "cobra"} <= dev
    assert runtime < dev
    assert {"pytest", "ruff", "httpx2", "streamlit", "cobra"}.isdisjoint(runtime)


def test_build_backend_is_exactly_pinned():
    cfg = tomllib.loads((_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    assert cfg["build-system"]["requires"] == ["setuptools==83.0.0", "wheel==0.47.0"]
