def _json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _canonical(value: object) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":")) + "\n").encode()


def _sha(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _minimal_wheel(
    name: str,
    version: str,
    *,
    license_expression: str = "MIT",
    raw_license_header: bytes | None = None,
    vendored_dist_info: bool = False,
    dist_info_distribution: str | None = None,
) -> bytes:
    distribution = (dist_info_distribution or name).replace("-", "_")
    dist_info = f"{distribution}-{version}.dist-info"
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:

        def write_member(member_name: str, content: str | bytes) -> None:
            info = zipfile.ZipInfo(member_name, date_time=(2023, 11, 14, 22, 13, 20))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, content)

        metadata = (
            b"Metadata-Version: 2.4\n"
            + f"Name: {name}\nVersion: {version}\nLicense: ".encode()
            + raw_license_header
            + b"\n\n"
            if raw_license_header is not None
            else (
                f"Metadata-Version: 2.4\nName: {name}\nVersion: {version}\nLicense-Expression: {license_expression}\n\n"
            )
        )
        write_member(
            f"{dist_info}/METADATA",
            metadata,
        )
        write_member(
            f"{dist_info}/WHEEL",
            "Wheel-Version: 1.0\nGenerator: p30-test\nRoot-Is-Purelib: true\nTag: py3-none-any\n\n",
        )
        if vendored_dist_info:
            write_member(
                "fixture/_vendor/vendored-1.0.dist-info/METADATA",
                "Metadata-Version: 2.4\nName: vendored\nVersion: 1.0\n\n",
            )
            write_member(
                "fixture/_vendor/vendored-1.0.dist-info/WHEEL",
                "Wheel-Version: 1.0\nTag: py3-none-any\n\n",
            )
        write_member(f"{dist_info}/RECORD", "")
    return buffer.getvalue()


def _lock(path: Path, components: dict[tuple[str, str], bytes]) -> None:
    lines = [
        "#",
        "# This file is autogenerated by pip-compile with Python 3.13",
        "#",
    ]
    for (name, version), wheel in components.items():
        lines.extend(
            [
                f"{name}=={version} \\",
                f"    --hash=sha256:{_sha(wheel)}",
            ]
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _cache(cache_root: Path, wheels: list[bytes]) -> None:
    for index, wheel in enumerate(wheels):
        path = cache_root / f"{index:02d}" / f"wheel-{index}.body"
        path.parent.mkdir(parents=True)
        path.write_bytes(wheel)


def _materialized_wheelhouse(tmp_path: Path, *, source_date_epoch: int = 1_700_000_000) -> tuple[Path, Path]:
    tmp_path.mkdir(parents=True, exist_ok=True)
    wheel = _minimal_wheel("fixture-lib", "1.2.3")
    lock = tmp_path / "runtime-py313.lock"
    cache_root = tmp_path / "cache"
    cache_root.mkdir()
    output = tmp_path / "wheelhouse"
    _lock(lock, {("fixture-lib", "1.2.3"): wheel})
    _cache(cache_root, [wheel])
    release_candidate.materialize_wheelhouse(
        lock_paths=(lock,),
        cache_root=cache_root,
        output_dir=output,
        source_date_epoch=source_date_epoch,
        target_profile="linux_arm64_cp313",
    )
    return lock, output


def _git(repo: Path, *args: str, env: dict[str, str] | None = None) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    return result.stdout.strip()


