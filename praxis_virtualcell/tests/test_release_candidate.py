def test_extra_top_level_dist_info_is_not_accepted_as_cached_wheel_identity(tmp_path: Path) -> None:
    buffer = io.BytesIO(_minimal_wheel("fixture-lib", "1.2.3"))
    with zipfile.ZipFile(buffer, "a", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("unexpected-1.0.dist-info/RECORD", "")
    wheel = buffer.getvalue()
    lock = tmp_path / "runtime-py313.lock"
    cache_root = tmp_path / "cache"
    _lock(lock, {("fixture-lib", "1.2.3"): wheel})
    _cache(cache_root, [wheel])

    with pytest.raises(release_candidate.ReleaseContractError, match="incomplete"):
        release_candidate.materialize_wheelhouse(
            lock_paths=(lock,),
            cache_root=cache_root,
            output_dir=tmp_path / "wheelhouse",
            source_date_epoch=1_700_000_000,
            target_profile="linux_arm64_cp313",
        )


