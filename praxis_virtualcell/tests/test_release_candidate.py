def _oci_archive(
    path: Path,
    *,
    layer: bytes = b"layer",
    tar_mtime: int = 1,
    source_sha: str | None = None,
    product_version: str | None = None,
) -> None:
    config: dict[str, object] = {"architecture": "arm64", "os": "linux"}
    if source_sha is not None and product_version is not None:
        config["config"] = {
            "Labels": {
                "org.opencontainers.image.revision": source_sha,
                "org.opencontainers.image.version": product_version,
            }
        }
    config_bytes = _canonical(config)
    config_digest = _sha(config_bytes)
    layer_digest = _sha(layer)
    manifest = _canonical(
        {
            "schemaVersion": 2,
            "mediaType": "application/vnd.oci.image.manifest.v1+json",
            "config": {
                "mediaType": "application/vnd.oci.image.config.v1+json",
                "digest": f"sha256:{config_digest}",
                "size": len(config_bytes),
            },
            "layers": [
                {
                    "mediaType": "application/vnd.oci.image.layer.v1.tar",
                    "digest": f"sha256:{layer_digest}",
                    "size": len(layer),
                }
            ],
        }
    )
    manifest_digest = _sha(manifest)
    index = _canonical(
        {
            "schemaVersion": 2,
            "manifests": [
                {
                    "mediaType": "application/vnd.oci.image.manifest.v1+json",
                    "digest": f"sha256:{manifest_digest}",
                    "size": len(manifest),
                }
            ],
        }
    )
    entries = {
        "index.json": index,
        f"blobs/sha256/{manifest_digest}": manifest,
        f"blobs/sha256/{config_digest}": config_bytes,
        f"blobs/sha256/{layer_digest}": layer,
    }
    with tarfile.open(path, "w") as archive:
        for name, data in entries.items():
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mtime = tar_mtime
            archive.addfile(info, io.BytesIO(data))


