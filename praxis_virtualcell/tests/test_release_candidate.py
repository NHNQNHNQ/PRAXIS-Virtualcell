def test_missing_or_misbound_cached_wheel_fails_closed(tmp_path: Path) -> None:
    expected = _minimal_wheel("expected-lib", "1.0.0")
    wrong = _minimal_wheel("wrong-lib", "1.0.0")
    lock = tmp_path / "runtime-py313.lock"
    cache_root = tmp_path / "cache"
    cache_root.mkdir()
    _lock(lock, {("expected-lib", "1.0.0"): expected})
    _cache(cache_root, [])
    with pytest.raises(release_candidate.ReleaseContractError, match="incomplete"):
        release_candidate.materialize_wheelhouse(
            lock_paths=(lock,),
            cache_root=cache_root,
            output_dir=tmp_path / "missing",
            source_date_epoch=1_700_000_000,
            target_profile="linux_arm64_cp313",
        )

    _lock(lock, {("expected-lib", "1.0.0"): wrong})
    _cache(cache_root, [wrong])
    with pytest.raises(release_candidate.ReleaseContractError, match="identity differs"):
        release_candidate.materialize_wheelhouse(
            lock_paths=(lock,),
            cache_root=cache_root,
            output_dir=tmp_path / "misbound",
            source_date_epoch=1_700_000_000,
            target_profile="linux_arm64_cp313",
        )


def test_nonexact_lock_output_reuse_and_symlink_inputs_are_rejected(
    tmp_path: Path,
) -> None:
    bad_lock = tmp_path / "bad.lock"
    bad_lock.write_text(
        "# autogenerated by pip-compile with Python 3.13\nfixture>=1\n",
        encoding="utf-8",
    )
    with pytest.raises(release_candidate.ReleaseContractError, match="non-exact"):
        release_candidate.parse_hash_lock(bad_lock)

    output = tmp_path / "not-empty"
    output.mkdir()
    (output / "old.whl").write_bytes(b"old")
    with pytest.raises(release_candidate.ReleaseContractError, match="absent or empty"):
        release_candidate._new_directory(output)
